import { expect, test } from '@playwright/test'
import { randomUUID } from 'node:crypto'

// Preparation uses API in the isolated Step 27 database. Navigation, messaging,
// filters and organisation below are exercised through Chromium's UI.
test('profile direct and product conversation, unread and responsive layout', async ({ browser }) => {
    const buyer = await browser.newContext({ baseURL: 'http://127.0.0.1:5179', viewport: { width: 390, height: 844 } })
    const seller = await browser.newContext({ baseURL: 'http://127.0.0.1:5179', viewport: { width: 390, height: 844 } })
    const suffix = randomUUID().replaceAll('-', '').slice(0, 8)
    const buyerName = `tester_b_${suffix}`, sellerName = `tester_s_${suffix}`
    const register = async (context: typeof buyer, username: string, phone: string) => {
        const response = await context.request.post('/api/auth/register', { data: { username, email: `${username}@example.com`, countryCode: 'UA', phone, password: 'StrongPassword1', passwordConfirmation: 'StrongPassword1' } })
        expect(response.status()).toBe(201)
        return (await response.json()).user
    }
    try {
        const buyerUser = await register(buyer, buyerName, `+38067${String(Math.floor(Math.random() * 1e7)).padStart(7, '0')}`)
        await register(seller, sellerName, `+38067${String(Math.floor(Math.random() * 1e7)).padStart(7, '0')}`)
        const categories = (await (await seller.request.get('/api/categories')).json()).categories
        const productResponse = await seller.request.post('/api/products', { data: { categoryId: categories.find((c: any) => c.code === 'grains').id, title: `Тестер зерно ${suffix} з довгою назвою для перевірки відображення на вузькому екрані`, quantity: 10, unit: 'kg', price: 20, currency: 'UAH', deliveryMode: 'pickup', deliveryOptions: [{ method: 'SELF_PICKUP' }], geoZone: 'Київ', status: 'active', photos: [] } })
        expect(productResponse.status()).toBe(201)
        const productId = (await productResponse.json()).product.id
        const page = await buyer.newPage()
        await page.goto(`/products/${productId}`)
        await page.getByRole('button', { name: /Написати продавцю/ }).click()
        await expect(page).toHaveURL(/\/messages\/[^/]+/)
        const productChat = page.url().split('/messages/')[1].split('?')[0]
        let simulateLostResponse = true
        await page.route(`**/api/conversations/${productChat}/messages`, async route => {
            if (route.request().method() === 'POST' && simulateLostResponse) {
                simulateLostResponse = false
                await route.fetch()
                await route.fulfill({ status: 503, json: { message: 'Тестовий збій відповіді' } })
            } else await route.continue()
        })
        await page.getByRole('textbox', { name: 'Повідомлення', exact: true }).fill(`Тест повідомлення ${suffix}`)
        await page.getByRole('button', { name: 'Надіслати', exact: true }).click()
        await expect(page.getByRole('alert')).toContainText('Тестовий збій відповіді')
        await page.getByRole('button', { name: 'Надіслати', exact: true }).click()
        await expect(page.locator('.deal-chat-history')).toContainText(`Тест повідомлення ${suffix}`)
        expect((await (await buyer.request.get(`/api/conversations/${productChat}/messages`)).json()).messages.filter((m: any) => m.body === `Тест повідомлення ${suffix}`)).toHaveLength(1)
        const sellerPage = await seller.newPage()
        await sellerPage.goto('/messages')
        const productRow = sellerPage.locator('.conversation-row').filter({ hasText: `Тестер зерно ${suffix}` })
        await expect(productRow.locator('.message-unread-count')).toBeVisible()
        await sellerPage.screenshot({ path: 'docs/qa/step-27/unread-390.png', fullPage: true })
        await productRow.click()
        await expect(sellerPage.locator('.deal-chat-history')).toContainText(`Тест повідомлення ${suffix}`)
        await expect.poll(async () => (await (await seller.request.get('/api/conversations')).json()).conversations.find((c: any) => c.id === productChat).unreadCount).toBe(0)
        await sellerPage.getByRole('button', { name: 'Повернутися до списку чатів' }).click()
        await sellerPage.getByRole('button', { name: /Продажі/ }).click()
        await expect(productRow).toBeVisible()
        await sellerPage.goto(`/profiles/${buyerUser.username}`)
        await sellerPage.getByRole('button', { name: 'Написати повідомлення', exact: true }).click()
        await expect(sellerPage).toHaveURL(/\/messages\/[^/]+/)
        const directChat = sellerPage.url().split('/messages/')[1].split('?')[0]
        expect(directChat).not.toBe(productChat)
        await expect(sellerPage.locator('.chat-context-header').getByText('Прямий чат', { exact: true })).toBeVisible()
        await sellerPage.getByRole('button', { name: 'Повернутися до списку чатів' }).click()
        await sellerPage.getByRole('button', { name: /Прямі чати/ }).click()
        await expect(sellerPage.locator('.conversation-row')).toHaveCount(1)
        await expect(productRow).toHaveCount(0)
        await sellerPage.screenshot({ path: 'docs/qa/step-27/direct-390.png', fullPage: true })
        const directRow = sellerPage.locator('.conversation-row').first()
        // Move the real trigger near the fixed navigation to exercise the
        // otherwise hard-to-reach bottom edge without modifying test accounts.
        const edgeTrigger = directRow.getByRole('button', { name: 'Дії з чатом' })
        await edgeTrigger.evaluate(element => {
            const nav = document.querySelector('.mobile-nav')!.getBoundingClientRect()
            const button = element.getBoundingClientRect()
            ;(element as HTMLElement).style.transform = `translateY(${nav.top - 140 - button.bottom}px)`
        })
        await edgeTrigger.click()
        const edgePopup = await sellerPage.getByRole('menu').boundingBox()
        const mobileNav = await sellerPage.locator('.mobile-nav').boundingBox()
        expect(edgePopup!.y + edgePopup!.height).toBeLessThanOrEqual(mobileNav!.y)
        await sellerPage.screenshot({ path: 'docs/qa/step-27/menu-bottom-390.png', fullPage: true })
        await sellerPage.keyboard.press('Escape')
        await edgeTrigger.evaluate(element => { (element as HTMLElement).style.transform = '' })
        await directRow.getByRole('button', { name: 'Дії з чатом' }).click()
        await sellerPage.getByRole('menuitem', { name: 'Додати в збережене' }).click()
        await sellerPage.getByRole('button', { name: 'Збережені', exact: true }).click()
        await expect(sellerPage.locator('.conversation-row')).toHaveCount(1)
        await sellerPage.locator('.conversation-row').first().getByRole('button', { name: 'Дії з чатом' }).click()
        await sellerPage.getByRole('menuitem', { name: 'Перемістити в кошик' }).click()
        await sellerPage.getByRole('button', { name: 'Перемістити', exact: true }).click()
        await sellerPage.getByRole('button', { name: 'Кошик', exact: true }).click()
        await expect(sellerPage.locator('.conversation-row')).toHaveCount(1)
        await sellerPage.screenshot({ path: 'docs/qa/step-27/trash-390.png', fullPage: true })
        await sellerPage.locator('.conversation-row').first().getByRole('button', { name: 'Дії з чатом' }).click()
        await sellerPage.getByRole('menuitem', { name: 'Відновити з кошика' }).click()
        for (const width of [320, 390, 768, 1024, 1280, 1440]) {
            await sellerPage.setViewportSize({ width, height: 900 })
            await sellerPage.goto(`/messages/${directChat}`)
            await expect(sellerPage.getByRole('textbox', { name: 'Повідомлення', exact: true })).toBeVisible()
            await expect(sellerPage.locator('.chat-context-header')).toContainText(buyerName)
            expect(await sellerPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
            if (width <= 390) {
                const input = await sellerPage.getByRole('textbox', { name: 'Повідомлення', exact: true }).boundingBox()
                const nav = await sellerPage.locator('.mobile-nav').boundingBox()
                expect(input!.y + input!.height).toBeLessThanOrEqual(nav!.y)
            }
            await sellerPage.locator('.chat-context-header').getByRole('button', { name: 'Дії з чатом' }).click()
            const popup = await sellerPage.getByRole('menu').boundingBox()
            expect(popup!.x).toBeGreaterThanOrEqual(0)
            expect(popup!.x + popup!.width).toBeLessThanOrEqual(width)
            expect(popup!.y).toBeGreaterThanOrEqual(0)
            if (width <= 390) {
                const nav = await sellerPage.locator('.mobile-nav').boundingBox()
                expect(popup!.y + popup!.height).toBeLessThanOrEqual(nav!.y)
            } else expect(popup!.y + popup!.height).toBeLessThanOrEqual(900)
            if (width === 320 || width === 1280) await sellerPage.screenshot({ path: `docs/qa/step-27/menu-${width}.png`, fullPage: true })
            await sellerPage.keyboard.press('Escape')
            await sellerPage.screenshot({ path: `docs/qa/step-27/dialog-${width}.png`, fullPage: true })
        }
        await sellerPage.setViewportSize({ width: 1280, height: 900 })
        await sellerPage.goto('/messages')
        await sellerPage.getByRole('textbox', { name: 'Пошук у повідомленнях' }).fill(`Тестер зерно ${suffix}`)
        await expect(sellerPage.locator('.conversation-row')).toHaveCount(1)
        const trigger = sellerPage.locator('.conversation-row').getByRole('button', { name: 'Дії з чатом' })
        await trigger.focus()
        await sellerPage.keyboard.press('Enter')
        await expect(sellerPage.getByRole('menu')).toBeVisible()
        await sellerPage.keyboard.press('Escape')
        await expect(sellerPage.getByRole('menu')).toHaveCount(0)
        await expect(trigger).toBeFocused()
        await sellerPage.keyboard.press('Space')
        const menu = sellerPage.getByRole('menu')
        await expect(menu).toBeVisible()
        const bounds = await menu.boundingBox()
        expect(bounds!.x).toBeGreaterThanOrEqual(0)
        expect(bounds!.y).toBeGreaterThanOrEqual(0)
        expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(1280)
        expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(900)
        await sellerPage.keyboard.press('Escape')
        await sellerPage.screenshot({ path: 'docs/qa/step-27/search-1280.png', fullPage: true })

        // Additional contextual fixtures are prepared by API, then inspected in the UI.
        const requestResponse = await buyer.request.post('/api/buy-requests', { data: { categoryId: categories.find((c: any) => c.code === 'grains').id, title: `Запит тестер ${suffix}`, description: '', delivery: 'no', minPrice: 0, maxPrice: 150, quantity: 10, unit: 'kg', currency: 'UAH', geoArea: 'Київська область', fulfillmentMode: 'multiple_sellers' } })
        expect(requestResponse.status()).toBe(201)
        const requestId = (await requestResponse.json()).buyRequest.id
        const requestConversation = await seller.request.post(`/api/buy-requests/${requestId}/conversation`)
        expect(requestConversation.ok()).toBeTruthy()
        const offerResponse = await seller.request.post(`/api/buy-requests/${requestId}/offers`, { data: { quantity: 10, unit: 'kg', price: 145, currency: 'UAH', delivery: 'Самовивіз' } })
        expect(offerResponse.status()).toBe(201)
        const offerId = (await offerResponse.json()).offer.id
        const offerConversation = await buyer.request.post(`/api/offers/${offerId}/conversation`)
        expect(offerConversation.ok()).toBeTruthy()
        const offerChatId = (await offerConversation.json()).conversation.id
        const deal = await buyer.request.post(`/api/offers/${offerId}/accept`, { data: { quantity: 5, selectionKey: randomUUID() } })
        expect(deal.status()).toBe(201)
        const orderId = (await deal.json()).order.id
        expect((await (await seller.request.get(`/api/orders/${orderId}/conversation`)).json()).conversation.id).toBe(offerChatId)
        await sellerPage.goto('/messages')
        await sellerPage.getByRole('textbox', { name: 'Пошук у повідомленнях' }).fill(`Запит тестер ${suffix}`)
        await expect(sellerPage.locator('.conversation-row')).toHaveCount(2)
        await expect(sellerPage.locator('.conversation-row').filter({ hasText: 'Пропозиція продавця' })).toHaveCount(1)
        await expect(sellerPage.locator('.conversation-row').filter({ hasText: 'Запит на покупку' })).toHaveCount(1)
        await sellerPage.screenshot({ path: 'docs/qa/step-27/context-1280.png', fullPage: true })
        await page.goto('/discover')
        const otherBuyerPage = await buyer.newPage()
        await otherBuyerPage.goto('/discover')
        await sellerPage.goto(`/messages/${productChat}`)
        await expect(sellerPage.locator('.chat-context-header')).toContainText(`Тестер зерно ${suffix}`)
        const desktopText = `Відповідь продавця з desktop ${suffix}`
        await sellerPage.getByRole('textbox', { name: 'Повідомлення', exact: true }).fill(desktopText)
        await sellerPage.getByRole('button', { name: 'Надіслати', exact: true }).click()
        await expect(sellerPage.locator('.deal-chat-history')).toContainText(desktopText)
        await expect.poll(async () => (await (await buyer.request.get('/api/conversations')).json()).conversations.find((c: any) => c.id === productChat).unreadCount).toBeGreaterThan(0)
        await expect(otherBuyerPage.locator('.mobile-nav .message-unread-count')).toBeVisible({ timeout: 20000 })
        await page.setViewportSize({ width: 1280, height: 900 })
        await page.goto('/messages')
        await expect(page.locator('.conversation-row').filter({ hasText: desktopText })).toBeVisible()
        await page.locator('.conversation-row').filter({ hasText: desktopText }).click()
        await expect(page.locator('.deal-chat-history')).toContainText(desktopText)
        await expect.poll(async () => (await (await buyer.request.get('/api/conversations')).json()).conversations.find((c: any) => c.id === productChat).unreadCount).toBe(0)
        await expect(otherBuyerPage.locator('.mobile-nav .message-unread-count')).toHaveCount(0, { timeout: 20000 })
        await otherBuyerPage.close()
        await page.goto(`/profiles/${sellerName}`)
        await page.getByRole('button', { name: 'Написати повідомлення', exact: true }).click()
        await expect(page).toHaveURL(new RegExp(`/messages/${directChat}`))
        await page.getByRole('button', { name: /Прямі чати/ }).click()
        await expect(page.locator('.conversation-row')).toHaveCount(1)
        await expect(page.locator('.conversation-row').filter({ hasText: `Тестер зерно ${suffix}` })).toHaveCount(0)
        await page.locator('.conversation-row').first().getByRole('button', { name: 'Дії з чатом' }).click()
        await page.getByRole('menuitem', { name: 'Додати в збережене' }).click()
        await page.getByRole('button', { name: 'Збережені', exact: true }).click()
        await expect(page.locator('.conversation-row')).toHaveCount(1)
        await page.locator('.conversation-row').first().getByRole('button', { name: 'Дії з чатом' }).click()
        await page.getByRole('menuitem', { name: 'Перемістити в кошик' }).click()
        await page.getByRole('button', { name: 'Перемістити', exact: true }).click()
        await page.getByRole('button', { name: 'Кошик', exact: true }).click()
        await expect(page.locator('.conversation-row')).toHaveCount(1)
        await page.locator('.conversation-row').first().getByRole('button', { name: 'Дії з чатом' }).click()
        await page.getByRole('menuitem', { name: 'Відновити з кошика' }).click()
    } finally { await buyer.close(); await seller.close() }
})
