  const page = await context.newPage()
  await page.addInitScript(() => { localStorage.setItem('deshchotreba-onboarding-v1', 'done'); localStorage.setItem('pwa-install-dismissed', '1'); window.__pwaOfferCount = 0; window.addEventListener('pwa:offer-install', () => window.__pwaOfferCount++) })
