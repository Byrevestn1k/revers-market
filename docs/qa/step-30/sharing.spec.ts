import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'

test('public sharing, initial metadata and responsive layout', async ({ browser, request }) => {
    const seller = await browser.newContext({ baseURL: 'http://127.0.0.1:5182', permissions: ['clipboard-read', 'clipboard-write'] })
    const buyer = await browser.newContext({ baseURL: 'http://127.0.0.1:5182' })
    const suffix = randomUUID().replaceAll('-', '').slice(0, 8)
    const usernames = [`tester_s_${suffix}`, `tester_b_${suffix}`]
    for (const [i, context] of [seller, buyer].entries()) {
        const name = usernames[i]
        const response = await context.request.post('/api/auth/register', { data: { username: name, email: `${name}@example.com`, countryCode: 'UA', phone: `+38067${String(Math.floor(Math.random() * 1e7)).padStart(7, '0')}`, password: 'StrongPassword1', passwordConfirmation: 'StrongPassword1' } })
        expect(response.status()).toBe(201)
    }
    const avatar = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/a5sAAAAASUVORK5CYII='
    expect((await seller.request.patch('/api/profile/me', { data: { avatarUrl: avatar } })).status()).toBe(200)
    const profileShare = await (await request.get(`/api/share/profile/${usernames[0]}`)).json()
    const avatarResponse = await request.get(profileShare.previewImage)
    expect(avatarResponse.status()).toBe(200)
    expect(avatarResponse.headers()['content-type']).toContain('image/png')
    const categories = (await (await seller.request.get('/api/categories')).json()).categories
    const categoryId = categories.find((item: { code: string }) => item.code === 'grains').id
    const created = await seller.request.post('/api/products', { data: { categoryId, title: `Тест вулик ${suffix}`, description: 'Опис товару', quantity: 5, unit: 'kg', price: 100, currency: 'EUR', deliveryMode: 'pickup', geoZone: 'Київська область', status: 'active' } })
    expect(created.status()).toBe(201)
    const product = (await created.json()).product
    const productPayload = await (await request.get(`/api/share/product/${product.id}`)).json()
    expect(productPayload.previewImage).toContain('/brand/logo-mini.png')
    const fallbackImage = await request.get(productPayload.previewImage)
    expect(fallbackImage.status()).toBe(200)
    expect(fallbackImage.headers()['content-type']).toContain('image/png')
    const draftResponse = await seller.request.post('/api/products', { data: { categoryId, title: `Приватна чернетка ${suffix}`, description: 'Таємна чернетка', quantity: 1, unit: 'piece', price: 10, currency: 'UAH', deliveryMode: 'pickup', geoZone: 'Київська область', status: 'draft' } })
    expect(draftResponse.status()).toBe(201)
    const draft = (await draftResponse.json()).product
    expect((await request.get(`/api/share/product/${draft.id}`)).status()).toBe(404)
    const draftHtml = await request.get(`/products/${draft.id}`)
    expect(draftHtml.status()).toBe(404)
    expect(await draftHtml.text()).not.toContain('Таємна чернетка')
    expect((await seller.request.get(`/api/products/${draft.id}`)).status()).toBe(200)
    expect((await seller.request.get(`/products/${draft.id}`)).status()).toBe(200)
    const createdRequest = await buyer.request.post('/api/buy-requests', { data: { categoryId, title: `Шукаю ${suffix}`, description: 'Потрібно', delivery: 'no', maxPrice: 150, quantity: 10, unit: 'kg', currency: 'UAH', geoArea: 'Київська область', fulfillmentMode: 'multiple_sellers' } })
    expect(createdRequest.status()).toBe(201)
    const item = (await createdRequest.json()).buyRequest
    const requestPayload = await (await request.get(`/api/share/buy_request/${item.id}`)).json()
    expect(requestPayload.shareText).toContain('10 кг')
    expect(requestPayload.shareText).toContain('150 UAH')
    expect(requestPayload.publicUrl).toContain(`/buy-requests/${item.id}`)
    for (const path of [`/products/${product.id}`, `/buy-requests/${item.id}`, `/profiles/${usernames[0]}`]) {
        const response = await request.get(path)
        expect(response.status()).toBe(200)
        const html = await response.text()
        expect(html).toContain('property="og:title"')
        expect(html).toContain('property="og:image"')
        expect(html).toContain('name="twitter:card"')
        expect(html).toContain('http://127.0.0.1:5182/')
    }
    const forgedHost = await request.get(`http://127.0.0.1:3110/products/${product.id}`, { headers: { Host: 'attacker.example' } })
    expect(await forgedHost.text()).not.toContain('attacker.example')
    const page = await seller.newPage()
    await page.addInitScript(() => { Object.defineProperty(navigator, 'share', { configurable: true, value: (data: unknown) => { (window as any).__shared = data; return Promise.resolve() } }) })
    for (const width of [320, 390, 768, 1024, 1280, 1440]) {
        await page.setViewportSize({ width, height: 900 })
        await page.goto(`/products/${product.id}`)
        await page.locator('.app-shell').waitFor({ state: 'attached' })
        await page.getByRole('heading', { name: product.title }).waitFor()
        await expect(page.locator('.listing-person-card strong').first()).toHaveText(usernames[0])
        await page.getByRole('button', { name: 'Поділитися' }).first().click()
        const menu = page.getByRole('group', { name: 'Способи поширення' })
        await expect(menu.getByText('Telegram')).toBeVisible()
        if (width === 320) {
            await page.keyboard.press('Escape')
            await expect(menu).toHaveCount(0)
            await expect(page.getByRole('button', { name: 'Поділитися' }).first()).toBeFocused()
            await page.keyboard.press('Enter')
            await expect(menu.getByText('Telegram')).toBeVisible()
        }
        const box = await menu.boundingBox()
        expect(box && box.x >= 0 && box.x + box.width <= width).toBeTruthy()
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
        await expect(menu.getByText('Telegram')).toHaveAttribute('href', /t\.me\/share\/url/)
        await expect(menu.getByText('Viber')).toHaveAttribute('href', /^viber:\/\/forward/)
        await expect(menu.getByText('Facebook')).toHaveAttribute('href', /facebook\.com\/sharer/)
        const telegram = new URL((await menu.getByText('Telegram').getAttribute('href'))!)
        expect(telegram.searchParams.get('url')).toContain(product.id)
        expect(telegram.searchParams.get('text')).toContain(product.title)
        const viber = new URL((await menu.getByText('Viber').getAttribute('href'))!)
        expect(viber.searchParams.get('text')).toContain(product.id)
        const facebook = new URL((await menu.getByText('Facebook').getAttribute('href'))!)
        expect(facebook.searchParams.get('u')).toContain(product.id)
        await menu.getByRole('button', { name: 'Системне меню' }).click()
        expect(await page.evaluate(() => (window as any).__shared.url)).toContain(product.id)
        await menu.getByRole('button', { name: 'Копіювати текст із посиланням' }).click()
        await expect(menu.getByRole('status')).toHaveText('Скопійовано')
        expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('100 EUR')
        await page.screenshot({ path: `docs/qa/step-30/product-${width}.png` })
    }
    await page.evaluate(() => Object.defineProperty(navigator, 'share', { configurable: true, value: () => Promise.reject(new DOMException('Cancelled', 'AbortError')) }))
    await page.getByRole('group', { name: 'Способи поширення' }).getByRole('button', { name: 'Системне меню' }).click()
    await expect(page.getByRole('group', { name: 'Способи поширення' }).getByRole('status')).toHaveCount(0)
    await page.evaluate(() => Object.defineProperty(navigator.clipboard, 'writeText', { configurable: true, value: () => Promise.reject(new Error('denied')) }))
    await page.getByRole('group', { name: 'Способи поширення' }).getByRole('button', { name: 'Копіювати посилання' }).click()
    await expect(page.getByRole('group', { name: 'Способи поширення' }).getByRole('status')).toContainText('Не вдалося скопіювати')
    for (const [label, path] of [['request', `/buy-requests/${item.id}`], ['profile', `/profiles/${usernames[0]}`]]) {
        for (const width of [320, 390, 768, 1024, 1280, 1440]) {
            await page.setViewportSize({ width, height: 900 })
            await page.goto(path)
            await page.getByRole('button', { name: 'Поділитися' }).first().click()
            const menu = page.getByRole('group', { name: 'Способи поширення' })
            await expect(menu.getByText('Telegram')).toBeVisible()
            const box = await menu.boundingBox()
            expect(box && box.x >= 0 && box.x + box.width <= width).toBeTruthy()
            expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
            if (width === 390 || width === 1280) await page.screenshot({ path: `docs/qa/step-30/${label}-${width}.png` })
        }
    }
    await page.goto(`/profiles/${usernames[0]}`)
    for (const width of [320, 390, 768, 1024, 1280, 1440]) {
        await page.setViewportSize({ width, height: 900 })
        await page.locator('.product-card').first().getByRole('button', { name: 'Поділитися' }).click()
        await expect(page.getByRole('group', { name: 'Способи поширення' }).getByText('Telegram')).toBeVisible()
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
        await page.keyboard.press('Escape')
    }
    await page.goto(`/profiles/${usernames[1]}`)
    await page.getByRole('tab', { name: /Запити на покупку/ }).click()
    for (const width of [320, 390, 768, 1024, 1280, 1440]) {
        await page.setViewportSize({ width, height: 900 })
        await page.locator('.buy-request-card').first().getByRole('button', { name: 'Поділитися' }).click()
        await expect(page.getByRole('group', { name: 'Способи поширення' }).getByText('Telegram')).toBeVisible()
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
        await page.keyboard.press('Escape')
    }
    const offerResponse = await seller.request.post(`/api/buy-requests/${item.id}/offers`, { data: { requestKey: randomUUID(), quantity: 10, unit: 'kg', price: 100, currency: 'UAH', delivery: 'Самовивіз' } })
    expect(offerResponse.status()).toBe(201)
    const offer = (await offerResponse.json()).offer
    const accepted = await buyer.request.post(`/api/offers/${offer.id}/accept`, { data: { expectedRevision: offer.revision, quantity: 10, selectionKey: randomUUID() } })
    expect(accepted.status()).toBe(201)
    const order = (await accepted.json()).order.id
    expect((await seller.request.post(`/api/orders/${order}/seller-confirm`)).status()).toBe(200)
    expect((await buyer.request.post(`/api/orders/${order}/complete`, { data: { actualQuantity: 10 } })).status()).toBe(200)
    expect((await seller.request.post(`/api/orders/${order}/complete`)).status()).toBe(200)
    const first = await buyer.request.post(`/api/orders/${order}/reviews`, { data: { rating: 11, body: 'Публічний відгук' } })
    expect(first.status()).toBe(201)
    const reviewId = (await first.json()).review.id
    expect((await request.get(`/api/share/review/${usernames[0]}?review=${reviewId}`)).status()).toBe(404)
    expect((await seller.request.post(`/api/orders/${order}/reviews`, { data: { rating: 9, body: 'Дякую' } })).status()).toBe(201)
    const reviewShare = await request.get(`/api/share/review/${usernames[0]}?review=${reviewId}`)
    expect(reviewShare.status()).toBe(200)
    expect(await reviewShare.text()).not.toContain(order)
    const reviewHtml = await (await request.get(`/profiles/${usernames[0]}?review=${reviewId}`)).text()
    expect(reviewHtml).toContain('Публічний відгук')
    expect(reviewHtml).not.toContain(order)
    await page.goto(`/profiles/${usernames[0]}?review=${reviewId}`)
    await expect(page.locator(`#review-${reviewId}`)).toContainText('Публічний відгук')
    await page.locator(`#review-${reviewId}`).getByRole('button', { name: 'Поділитися' }).click()
    await expect(page.getByRole('group', { name: 'Способи поширення' }).getByText('Telegram')).toBeVisible()
    for (const width of [320, 390, 768, 1024, 1280, 1440]) {
        await page.setViewportSize({ width, height: 900 })
        const box = await page.getByRole('group', { name: 'Способи поширення' }).boundingBox()
        expect(box && box.x >= 0 && box.x + box.width <= width).toBeTruthy()
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
        if (width === 390 || width === 1280) await page.screenshot({ path: `docs/qa/step-30/review-${width}.png` })
    }
    const closed = await request.get(`/api/share/buy_request/${item.id}`)
    expect(closed.status()).toBe(404)
    const closedHtml = await request.get(`/buy-requests/${item.id}`)
    expect(closedHtml.status()).toBe(404)
    expect(await closedHtml.text()).not.toContain(item.title)
    expect((await buyer.request.get(`/buy-requests/${item.id}`)).status()).toBe(200)
    const withoutShare = await buyer.newPage()
    await withoutShare.addInitScript(() => { Object.defineProperty(navigator, 'share', { configurable: true, value: undefined }) })
    await withoutShare.goto(`/products/${product.id}`)
    await withoutShare.getByRole('button', { name: 'Поділитися' }).first().click()
    await expect(withoutShare.getByRole('group', { name: 'Способи поширення' }).getByText('Telegram')).toBeVisible()
    await expect(withoutShare.getByRole('button', { name: 'Системне меню' })).toHaveCount(0)
    await seller.close(); await buyer.close()
})
