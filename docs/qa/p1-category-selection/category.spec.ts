import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { writeFileSync } from 'node:fs'

test('tree, search, recommendations and persisted category on product and request', async ({ browser }) => {
    const context = await browser.newContext({ baseURL: 'http://127.0.0.1:5182' })
    const suffix = randomUUID().replaceAll('-', '').slice(0, 8), username = `p1cat_${suffix}`
    const registered = await context.request.post('/api/auth/register', { data: { username, email: `${username}@example.com`, countryCode: 'UA', phone: `+38067${String(Math.floor(Math.random() * 1e7)).padStart(7, '0')}`, password: 'StrongPassword1', passwordConfirmation: 'StrongPassword1' } })
    expect(registered.status()).toBe(201)
    const settlements = (await (await context.request.get('/api/settlements?q=Рівне')).json()).settlements
    const rivne = settlements.find((item: any) => item.name === 'Рівне' && item.region === 'Рівненська область')
    expect((await context.request.patch('/api/profile/me', { data: { location: 'Рівне', settlementCode: rivne.code, mapLocation: { mode: 'pin', latitude: 50.625951, longitude: 26.270642, consent: true } } })).status()).toBe(200)
    const categories = (await (await context.request.get('/api/categories')).json()).categories
    const grain = categories.find((item: any) => item.code === 'grains')
    const smartphone = categories.find((item: any) => item.code === 'market-electronics--telefony-ta-aksesuary--smartfony-mobilni-telefony')
    const smartphoneTrail: string[] = []
    for (let current = smartphone; current; current = categories.find((item: any) => item.id === current.parentId)) smartphoneTrail.unshift(current.name)
    const smartphoneLabel = smartphoneTrail.join(' › ')
    const root = categories.find((item: any) => item.name === 'Дитячий світ' && !item.parentId)
    const middle = categories.find((item: any) => item.name === 'Дитячий одяг' && item.parentId === root.id)
    const leaf = categories.find((item: any) => item.name === 'Одяг для хлопчиків' && item.parentId === middle.id)
    const errors: string[] = [], failures: string[] = [], consoleErrors: { text: string; url: string }[] = [], networkFailures: { error: string; url: string }[] = []
    const page = await context.newPage()
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') consoleErrors.push({ text: message.text(), url: message.location().url }) })
    page.on('requestfailed', request => {
        const url = new URL(request.url()), error = request.failure()?.errorText ?? 'unknown'
        if (error !== 'net::ERR_ABORTED') networkFailures.push({ error, url: url.origin + url.pathname })
        if (url.pathname.startsWith('/api/categories') && error !== 'net::ERR_ABORTED') failures.push(`${error} ${url.pathname}`)
    })
    page.on('response', response => { if (response.url().includes('/api/categories') && response.status() >= 400) failures.push(`${response.status()} ${new URL(response.url()).pathname}`) })
    const picker = page.getByRole('combobox', { name: 'Пошук або вибір категорії' })
    const chooseGrain = async () => {
        await picker.fill(grain.name)
        const select = page.getByRole('button', { name: `Вибрати категорію ${grain.name}` }).filter({ visible: true })
        if (await select.count()) await select.first().click()
        else await page.getByRole('option').filter({ hasText: grain.name }).filter({ visible: true }).first().click()
        await expect(page.locator('.category-picker input[type=hidden]')).toHaveValue(grain.id)
    }
    for (const width of [320, 390, 768, 1280, 1440]) {
        await page.setViewportSize({ width, height: 900 })
        for (const path of ['/my/products/new', '/my/requests/new']) {
            await page.goto(path); await page.locator('.app-shell').waitFor({ state: 'attached' }); await expect(picker).toBeEnabled()
            await picker.click()
            for (const item of [root, middle, leaf]) {
                const menu = page.locator('.category-picker-menu')
                const box = await menu.boundingBox()
                expect(box && box.x >= 0 && box.x + box.width <= width).toBeTruthy()
                expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
                await page.locator('.category-picker-mobile-tree [role=option]').getByText(item.name, { exact: true }).first().click()
            }
            await expect(page.locator('.category-picker input[type=hidden]')).toHaveValue(leaf.id)
            await expect(picker).toHaveValue(new RegExp(leaf.name))
            await chooseGrain()
            await expect(page.getByLabel('Культура або сорт')).toBeVisible()
            if (width === 390 || width === 1280) await page.screenshot({ path: `docs/qa/p1-category-selection/${path.includes('products') ? 'product' : 'request'}-${width}.png` })
        }
    }
    await page.setViewportSize({ width: 390, height: 900 })
    await page.goto('/my/products/new'); await page.locator('.app-shell').waitFor({ state: 'attached' })
    await page.getByLabel('Назва товару').fill(`Смартфон Samsung 128 ГБ ${suffix}`)
    const rec = page.locator('.category-recommendation button').filter({ hasText: 'Смартфони' }).first()
    await expect(rec).toBeVisible(); await chooseGrain()
    await expect(page.locator('.category-picker input[type=hidden]')).toHaveValue(grain.id)
    await expect(rec).toBeVisible()
    await page.getByLabel('Назва товару').fill(`Зерно продукт ${suffix}`)
    await page.getByLabel('Культура або сорт').fill('Пшениця')
    await picker.fill('Смартфони'); page.once('dialog', dialog => dialog.accept())
    const smartphoneRow = page.locator('.category-picker-row').filter({ has: page.getByRole('option', { name: smartphoneLabel, exact: true }) }).filter({ visible: true }).first()
    if (await smartphoneRow.locator('.category-picker-select-parent').count()) await smartphoneRow.locator('.category-picker-select-parent').click()
    else await smartphoneRow.getByRole('option').click()
    await expect(page.locator('.category-picker input[type=hidden]')).toHaveValue(smartphone.id)
    await chooseGrain(); await expect(page.getByLabel('Культура або сорт')).toHaveValue('Пшениця')
    await page.getByLabel('Ціна за одиницю').fill('100'); await page.getByLabel('Можна домовитися', { exact: true }).check()
    await page.getByRole('button', { name: 'Опублікувати товар' }).click(); await expect(page).toHaveURL(/\/my\/products$/)
    const product = (await (await context.request.get(`/api/products?ownerUsername=${username}`)).json()).products.find((item: any) => item.title.endsWith(suffix))
    expect(product.category.id).toBe(grain.id); expect(product.attributes.grain_type).toBe('Пшениця')
    await page.goto(`/my/products/${product.id}/edit`); await expect(page.locator('.category-picker input[type=hidden]')).toHaveValue(grain.id); await page.reload(); await expect(page.locator('.category-picker input[type=hidden]')).toHaveValue(grain.id)
    await picker.fill('Смартфони'); page.once('dialog', event => event.accept())
    const editSmartphone = page.locator('.category-picker-row').filter({ has: page.getByRole('option', { name: smartphoneLabel, exact: true }) }).filter({ visible: true }).first()
    if (await editSmartphone.locator('.category-picker-select-parent').count()) await editSmartphone.locator('.category-picker-select-parent').click()
    else await editSmartphone.getByRole('option').click()
    await expect(page.locator('.category-picker input[type=hidden]')).toHaveValue(smartphone.id)
    await chooseGrain(); await expect(page.getByLabel('Культура або сорт')).toHaveValue('Пшениця')
    await page.getByLabel('Назва товару').fill(`Зерно продукт змінено ${suffix}`)
    await page.getByRole('button', { name: 'Зберегти зміни' }).click(); await expect.poll(async () => (await (await context.request.get(`/api/products/${product.id}`)).json()).product.title).toContain('змінено')
    expect((await (await context.request.get(`/api/products/${product.id}`)).json()).product.category.id).toBe(grain.id)
    await page.goto('/my/requests/new'); await page.getByLabel('Назва товару').fill(`Зерно запит ${suffix}`); await chooseGrain()
    await page.getByLabel('Культура або сорт').fill('Жито'); await page.getByLabel('Можна домовитися', { exact: true }).check()
    await page.getByRole('button', { name: 'Опублікувати запит' }).click(); await expect(page).toHaveURL(/\/map$/)
    const item = (await (await context.request.get('/api/buy-requests?mine=true')).json()).buyRequests.find((entry: any) => entry.title.endsWith(suffix))
    expect(item.category.id).toBe(grain.id); expect(item.attributes.grain_type).toBe('Жито')
    await page.goto('/my/requests'); await page.locator('.buy-request-card').filter({ hasText: item.title }).getByRole('button', { name: 'Редагувати', exact: true }).click()
    const dialog = page.getByRole('dialog'); await expect(dialog.locator('.category-picker input[type=hidden]')).toHaveValue(grain.id); await expect(dialog.getByLabel('Культура або сорт')).toHaveValue('Жито')
    const dialogPicker = dialog.getByRole('combobox', { name: 'Пошук або вибір категорії' })
    await dialogPicker.fill('Смартфони'); page.once('dialog', event => event.accept())
    const dialogSmartphone = dialog.locator('.category-picker-row').filter({ has: page.getByRole('option', { name: smartphoneLabel, exact: true }) }).filter({ visible: true }).first()
    if (await dialogSmartphone.locator('.category-picker-select-parent').count()) await dialogSmartphone.locator('.category-picker-select-parent').click()
    else await dialogSmartphone.getByRole('option').click()
    await expect(dialog.locator('.category-picker input[type=hidden]')).toHaveValue(smartphone.id)
    await dialogPicker.fill(grain.name)
    const parentGrain = dialog.getByRole('button', { name: `Вибрати категорію ${grain.name}` }).filter({ visible: true })
    if (await parentGrain.count()) await parentGrain.first().click()
    else await dialog.getByRole('option').filter({ hasText: grain.name }).filter({ visible: true }).first().click()
    await expect(dialog.getByLabel('Культура або сорт')).toHaveValue('Жито')
    await dialog.getByLabel('Назва товару').fill(`Запит змінено ${suffix}`)
    await dialog.getByRole('button', { name: 'Зберегти', exact: true }).click(); await expect(dialog).toHaveCount(0)
    expect((await (await context.request.get(`/api/buy-requests/${item.id}`)).json()).buyRequest.category.id).toBe(grain.id)
    await page.reload(); await page.locator('.buy-request-card').filter({ hasText: `Запит змінено ${suffix}` }).getByRole('button', { name: 'Редагувати', exact: true }).click()
    await expect(page.getByRole('dialog').getByLabel('Культура або сорт')).toHaveValue('Жито')
    writeFileSync('docs/qa/p1-category-selection/browser-errors.json', JSON.stringify({ errors, failures, consoleErrors, networkFailures }, null, 2))
    const appConsoleErrors = consoleErrors.filter(entry => !(entry.text.includes('ERR_CONNECTION_TIMED_OUT') && /^https:\/\/[abc]\.tile\.openstreetmap\.org\//.test(entry.url)))
    expect(errors).toEqual([]); expect(failures).toEqual([]); expect(appConsoleErrors).toEqual([])
    await context.close()
})

test('seller offer keeps request category in creation and editing', async ({ browser }) => {
    const buyer = await browser.newContext({ baseURL: 'http://127.0.0.1:5182' })
    const seller = await browser.newContext({ baseURL: 'http://127.0.0.1:5182', viewport: { width: 390, height: 900 } })
    const suffix = randomUUID().replaceAll('-', '').slice(0, 8)
    for (const [index, context] of [buyer, seller].entries()) {
        const name = `p1offer_${index}_${suffix}`
        expect((await context.request.post('/api/auth/register', { data: { username: name, email: `${name}@example.com`, countryCode: 'UA', phone: `+38067${String(Math.floor(Math.random() * 1e7)).padStart(7, '0')}`, password: 'StrongPassword1', passwordConfirmation: 'StrongPassword1' } })).status()).toBe(201)
    }
    const categories = (await (await buyer.request.get('/api/categories')).json()).categories
    const category = categories.find((item: any) => item.code === 'grains')
    const created = await buyer.request.post('/api/buy-requests', { data: { categoryId: category.id, title: `Запит пропозиція ${suffix}`, description: 'Тест', quantity: 20, unit: 'kg', currency: 'UAH', maxPrice: 230, countryCode: 'UA', receiptMethod: 'SELF_PICKUP', geoArea: 'Рівне', fulfillmentMode: 'multiple_sellers', attributes: { grain_type: 'Жито' } } })
    expect(created.status()).toBe(201)
    const id = (await created.json()).buyRequest.id
    const page = await seller.newPage()
    await page.goto(`/buy-requests/${id}`)
    await page.getByRole('button', { name: 'Запропонувати товар' }).click()
    const form = page.locator('.seller-offer-form')
    await expect(form.getByLabel('Культура або сорт')).toHaveValue('Жито')
    await expect(form.getByRole('combobox', { name: 'Пошук або вибір категорії' })).toHaveCount(0)
    await form.getByLabel('Можна домовитися', { exact: true }).check()
    await form.getByRole('button', { name: 'Переглянути умови' }).click()
    await form.getByRole('button', { name: 'Надіслати пропозицію' }).click()
    await expect(page.getByRole('button', { name: 'Запропонувати товар' })).toBeVisible()
    const offers = (await (await buyer.request.get(`/api/buy-requests/${id}/offers`)).json()).offers
    expect(offers).toHaveLength(1); expect(offers[0].attributes.grain_type).toBe('Жито')
    await page.goto(`/requests?offer=${offers[0].id}`)
    const card = page.locator('.request-card').filter({ hasText: `Запит пропозиція ${suffix}` })
    await card.getByRole('button', { name: 'Редагувати', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog.getByRole('combobox', { name: 'Пошук або вибір категорії' })).toHaveCount(0)
    await expect(dialog.getByLabel('Культура або сорт')).toHaveValue('Жито')
    await dialog.locator('input[name="price"]').fill('205')
    await dialog.getByRole('button', { name: 'Зберегти пропозицію' }).click(); await expect(dialog).toHaveCount(0)
    const updated = (await (await buyer.request.get(`/api/buy-requests/${id}/offers`)).json()).offers[0]
    expect(updated.attributes.grain_type).toBe('Жито'); expect(updated.price.amount).toBe(205)
    await buyer.close(); await seller.close()
})

